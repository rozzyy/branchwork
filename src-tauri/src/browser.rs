//! Browser screen (M11): one native child webview per tab, placed by the
//! frontend over the Browser pane. Browser webviews are labelled
//! `browser-<window>-<tab>`, carry no capability (see `capabilities/`), may
//! only navigate to http(s), and every command acts only on the calling
//! window's own browser webviews.

use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use serde::Serialize;
use tauri::webview::{PageLoadEvent, PermissionResponse};
use tauri::{Emitter, LogicalPosition, LogicalSize, Manager, Rect, Url, Webview, WebviewBuilder, WebviewUrl, Window};

use crate::error::AppError;

pub const LABEL_PREFIX: &str = "browser-";
const MAX_URL_LEN: usize = 2048;
/// Logical px bound for webview position and size.
const MAX_COORD: f64 = 20_000.0;
/// Title updates from one page are sent at most this often.
const TITLE_INTERVAL: Duration = Duration::from_millis(150);

/// Payload of the `browser:state` event, sent to the owning window only.
#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct BrowserState {
    pub tab_id: String,
    pub url: String,
    pub title: Option<String>,
    pub loading: Option<bool>,
}

/// Tab ids are generated by the frontend: 1–40 of `[a-z0-9-]`.
pub fn valid_tab_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 40 && id.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

/// Only absolute http(s) URLs with a host are loaded.
pub fn parse_url(raw: &str) -> Result<Url, AppError> {
    let raw = raw.trim();
    if raw.is_empty() || raw.len() > MAX_URL_LEN {
        return Err(AppError::validation("Invalid address"));
    }
    let url = Url::parse(raw).map_err(|_| AppError::validation("Invalid address"))?;
    if !matches!(url.scheme(), "http" | "https") || url.host_str().is_none_or(str::is_empty) {
        return Err(AppError::validation("Only http and https addresses can be opened"));
    }
    if crate::is_local_navigation(&url) {
        return Err(AppError::validation("Branchwork itself cannot be opened in a browser tab"));
    }
    Ok(url)
}

/// Navigation policy for browser webviews: http(s) and `about:`, but never
/// the app's own origin — Tauri trusts that origin (in dev the Vite server at
/// `localhost:1420`) with every command, so a page redirecting a tab there
/// would gain full IPC.
pub fn allows_navigation(url: &Url) -> bool {
    matches!(url.scheme(), "http" | "https" | "about") && !crate::is_local_navigation(url)
}

fn clamp(value: f64) -> f64 {
    if value.is_finite() { value.clamp(0.0, MAX_COORD) } else { 0.0 }
}

fn rect((x, y, w, h): (f64, f64, f64, f64)) -> Rect {
    Rect {
        position: LogicalPosition::new(clamp(x), clamp(y)).into(),
        size: LogicalSize::new(clamp(w).max(1.0), clamp(h).max(1.0)).into(),
    }
}

fn label(window: &Window, tab_id: &str) -> Result<String, AppError> {
    if !valid_tab_id(tab_id) {
        return Err(AppError::validation("Invalid browser tab id"));
    }
    Ok(format!("{LABEL_PREFIX}{}-{tab_id}", window.label()))
}

/// The caller's own browser webview for `tab_id`.
fn find(window: &Window, tab_id: &str) -> Result<Webview, AppError> {
    let label = label(window, tab_id)?;
    window
        .app_handle()
        .get_webview(&label)
        .filter(|webview| webview.window().label() == window.label())
        .ok_or_else(|| AppError::not_found("Browser tab is not open"))
}

fn emit(window_label: &str, webview: &Webview, state: BrowserState) {
    let _ = webview.app_handle().emit_to(window_label, "browser:state", state);
}

fn tab_of(label: &str, window_label: &str) -> String {
    label
        .strip_prefix(LABEL_PREFIX)
        .and_then(|rest| rest.strip_prefix(window_label))
        .and_then(|rest| rest.strip_prefix('-'))
        .unwrap_or_default()
        .to_owned()
}

/// Create the tab's webview (hidden) at the given logical bounds, or reuse it.
pub fn open(window: &Window, tab_id: &str, url: &str, bounds: (f64, f64, f64, f64)) -> Result<(), AppError> {
    let url = parse_url(url)?;
    if find(window, tab_id).is_ok() {
        return Ok(());
    }
    let label = label(window, tab_id)?;
    let owner = window.label().to_owned();
    let owner_for_title = owner.clone();
    // Last title sent and when, so a page retitling in a loop cannot flood.
    let last_title: Arc<Mutex<(Option<Instant>, String)>> = Arc::new(Mutex::new((None, String::new())));
    let builder = WebviewBuilder::new(&label, WebviewUrl::External(url))
        // Camera, microphone, geolocation, …: never granted to web pages.
        .on_permission_request(|_, _| PermissionResponse::Deny)
        .on_page_load(move |webview, payload| {
            let state = BrowserState {
                tab_id: tab_of(webview.label(), &owner),
                url: payload.url().to_string(),
                title: None,
                loading: Some(matches!(payload.event(), PageLoadEvent::Started)),
            };
            emit(&owner, &webview, state);
        })
        .on_document_title_changed(move |webview, title| {
            let title: String = title.chars().take(300).collect();
            {
                let mut last = last_title.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
                let recent = last.0.is_some_and(|at| at.elapsed() < TITLE_INTERVAL);
                if last.1 == title || recent {
                    return;
                }
                *last = (Some(Instant::now()), title.clone());
            }
            let state = BrowserState {
                tab_id: tab_of(webview.label(), &owner_for_title),
                url: webview.url().map(|url| url.to_string()).unwrap_or_default(),
                title: Some(title),
                loading: None,
            };
            emit(&owner_for_title, &webview, state);
        });
    let area = rect(bounds);
    let webview = window
        .add_child(builder, area.position, area.size)
        .map_err(|error| AppError::internal(format!("Could not open browser tab: {error}")))?;
    webview.hide().ok();
    Ok(())
}

pub fn set_bounds(window: &Window, tab_id: &str, bounds: (f64, f64, f64, f64)) -> Result<(), AppError> {
    find(window, tab_id)?
        .set_bounds(rect(bounds))
        .map_err(|error| AppError::internal(error.to_string()))
}

pub fn show(window: &Window, tab_id: &str, visible: bool) -> Result<(), AppError> {
    let webview = find(window, tab_id)?;
    let result = if visible { webview.show() } else { webview.hide() };
    result.map_err(|error| AppError::internal(error.to_string()))
}

pub fn navigate(window: &Window, tab_id: &str, url: &str) -> Result<(), AppError> {
    let url = parse_url(url)?;
    find(window, tab_id)?.navigate(url).map_err(|error| AppError::internal(error.to_string()))
}

pub fn go(window: &Window, tab_id: &str, action: &str) -> Result<(), AppError> {
    let webview = find(window, tab_id)?;
    let result = match action {
        "back" => webview.eval("history.back()"),
        "forward" => webview.eval("history.forward()"),
        "reload" => webview.reload(),
        _ => return Err(AppError::validation("Unknown browser action")),
    };
    result.map_err(|error| AppError::internal(error.to_string()))
}

pub fn close(window: &Window, tab_id: &str) -> Result<(), AppError> {
    match find(window, tab_id) {
        Ok(webview) => webview.close().map_err(|error| AppError::internal(error.to_string())),
        Err(_) => Ok(()),
    }
}

/// Close every browser webview owned by `window`.
pub fn close_all(window: &Window) -> Result<(), AppError> {
    let prefix = format!("{LABEL_PREFIX}{}-", window.label());
    for (label, webview) in window.app_handle().webviews() {
        if label.starts_with(&prefix) && webview.window().label() == window.label() {
            webview.close().ok();
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accepts_only_http_urls_with_a_host() {
        for ok in ["https://example.com", "http://localhost:3000/x?y=1", " https://a.b/c "] {
            assert!(parse_url(ok).is_ok(), "{ok}");
        }
        for bad in ["javascript:alert(1)", "file:///etc/passwd", "data:text/html,x", "tauri://localhost", "https://", "", "example.com"] {
            assert!(parse_url(bad).is_err(), "{bad}");
        }
        assert!(parse_url(&format!("https://a.com/{}", "x".repeat(MAX_URL_LEN))).is_err());
    }

    #[test]
    fn validates_tab_ids_and_navigation() {
        assert!(valid_tab_id("tab-1a"));
        for bad in ["", "Tab", "a/b", "a b", &"x".repeat(41)] {
            assert!(!valid_tab_id(bad), "{bad}");
        }
        assert!(allows_navigation(&Url::parse("https://x.com").unwrap()));
        assert!(!allows_navigation(&Url::parse("file:///x").unwrap()));
        assert!(!allows_navigation(&Url::parse("tauri://localhost").unwrap()));
        // The app's own origin is trusted by Tauri with every command.
        assert!(!allows_navigation(&Url::parse("tauri://localhost/index.html").unwrap()));
        if cfg!(debug_assertions) {
            assert!(!allows_navigation(&Url::parse("http://localhost:1420/").unwrap()));
            assert!(parse_url("http://localhost:1420").is_err());
        }
        assert!(allows_navigation(&Url::parse("http://localhost:3000/").unwrap()));
    }

    #[test]
    fn extracts_the_tab_from_a_label() {
        assert_eq!(tab_of("browser-ws-2-tab-7", "ws-2"), "tab-7");
        assert_eq!(tab_of("browser-main-t1", "main"), "t1");
    }
}
